import { defineCollection, z } from "astro:content";
import { glob } from 'astro/loaders';
import { TAG_KEYS } from './i18n/tags';

// Each post lives in its own folder: `index.md` is the original, and
// translations sit next to it as `index.<lang>.md` with a matching `lang`.
// Ids are `<lang>/<folder>` so every version of a post shares its folder slug.
function localizedId({ entry, data }: { entry: string; data: Record<string, unknown> }) {
  const folder = entry.split("/").slice(0, -1).join("/");
  const slug = folder.toLowerCase().replace(/\s+/g, "-");
  return `${data.lang ?? "fr"}/${slug}`;
}

const i18nFields = {
  lang: z.enum(["fr", "en"]).default("fr"),
  // Set on translations generated by an AI rather than written by hand.
  aiTranslated: z.boolean().default(false),
};

const blog = defineCollection({
  loader: glob({ pattern: '**/*.{md,mdx}', base: "./src/content/blog", generateId: localizedId }),
  schema: z.object({
    title: z.string(),
    description: z.string(),
    date: z.coerce.date(),
    draft: z.boolean().optional(),
    tags: z.array(z.enum(TAG_KEYS)).optional(),
    ...i18nFields,
  }),
});

const projects = defineCollection({
  loader: glob({ pattern: '**/*.{md,mdx}', base: "./src/content/projects", generateId: localizedId }),
  schema: z.object({
    title: z.string(),
    description: z.string(),
    date: z.coerce.date(),
    draft: z.boolean().optional(),
    demoURL: z.string().optional(),
    repoURL: z.string().optional(),
    ...i18nFields,
  }),
});

export const collections = { blog, projects };
